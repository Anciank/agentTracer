// Generate many list rows for virtualization demo (lazy; not in prod if unused)
export function makeManyTraces(n: number): TraceSummary[] {
  const out: TraceSummary[] = [...TRACES];
  for (let i = out.length; i < n; i++) {
    const err = i % 17 === 0;
    out.push({
      trace_id: `00000000-0000-4000-8000-${String(i).padStart(12, "0")}`,
      name: err ? `fail_${i}` : `run_${i}`,
      project: i % 3 === 0 ? "support" : i % 3 === 1 ? "research" : "local-dev",
      start: new Date(Date.UTC(2026, 9, 27, 12, 0, 0) - i * 60_000).toISOString().replace(".000Z", ".000Z"),
      end: new Date(Date.UTC(2026, 9, 27, 12, 0, 0) - i * 60_000 + 5000).toISOString().replace(".000Z", ".000Z"),
      duration_ms: 1000 + (i % 50) * 100,
      run_count: 2 + (i % 20),
      error_count: err ? 1 : 0,
      running_count: 0,
      status: err ? "error" : "success",
      tokens: T(100 + i, 50 + (i % 40)),
      model: i % 2 ? "gpt-4o-mini" : "gpt-4o",
      run_types: { chain: 1, llm: 1 + (i % 3), tool: i % 4 },
    });
  }
  return out;
}

